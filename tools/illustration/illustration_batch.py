#!/usr/bin/env python3
"""tools/illustration/illustration_batch.py — AI illustration batch generation.

Batch-generates AI illustrations through the Kaggle bridge, verifies the
manifest (job_id + sha256/bytes per file), applies the "Illustration" label
overlay, and writes a local manifest. Zero-cost: no paid routes, no API keys
handled here (KAGGLE_API_TOKEN is read by the kaggle CLI from the environment).

Stdlib + Pillow + the official `kaggle` CLI (network goes through the CLI).
"""
from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Tuple

from PIL import Image, ImageDraw, ImageFont

from tools.base_tool import (
    BaseTool,
    Determinism,
    ExecutionMode,
    ResourceProfile,
    ToolResult,
    ToolRuntime,
    ToolStability,
    ToolTier,
)

WIDTH, HEIGHT = 1280, 720
CHIP_TEXT = "Illustration"


def now_utc() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def apply_illustration_label(src: str | Path, dst: str | Path) -> Path:
    """Burn a semi-transparent 'Illustration' chip bottom-right of src -> dst."""
    src, dst = Path(src), Path(dst)
    with Image.open(src).convert("RGB") as img:
        overlay = Image.new("RGBA", img.size, (0, 0, 0, 0))
        d = ImageDraw.Draw(overlay)
        pad = 14
        font_size = 22
        try:
            font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", font_size)
        except Exception:
            font = ImageFont.load_default()
        tmp = Image.new("RGBA", (1, 1))
        td = ImageDraw.Draw(tmp)
        bbox = td.textbbox((0, 0), CHIP_TEXT, font=font)
        tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
        box = [img.width - tw - pad * 2, img.height - th - pad * 2,
               img.width - pad, img.height - pad]
        d.rounded_rectangle(box, radius=8, fill=(0, 0, 0, 150))
        d.text((box[0] + pad, box[1] + pad), CHIP_TEXT, font=font, fill=(255, 255, 255, 230))
        out = Image.alpha_composite(img.convert("RGBA"), overlay).convert("RGB")
        out.save(dst, optimize=True)
    return dst


def build_manifest(job_id: str, images: List[Tuple[Path, str, int, str, int]],
                   model: str, accelerator: str) -> Dict[str, Any]:
    """Build a multi-image manifest: job_id, generator=AI, rights_basis,
    images[{file, sha256, bytes, prompt, seed, width, height, model, ...}]."""
    ents = []
    for entry in images:
        if isinstance(entry, tuple):
            path, prompt, seed, w, h = entry
        else:
            path = entry
            prompt, seed, w, h = "", 0, 0, 0
        ents.append({
            "file": path.name,
            "sha256": sha256_file(path),
            "bytes": path.stat().st_size,
            "prompt": prompt,
            "seed": seed,
            "width": w,
            "height": h,
            "model": model,
            "rights_basis": "ai_generated_illustration",
            "generator": "AI",
        })
    return {
        "job_id": job_id,
        "generator": "AI",
        "rights_basis": "ai_generated_illustration",
        "model": model,
        "accelerator": accelerator,
        "images": ents,
        "created_utc": now_utc(),
    }


RUN_PY_TEMPLATE = '''#!/usr/bin/env python3
"""Kaggle-side illustration batch runner (generated by IllustrationBatchTool)."""
import hashlib, json, os, sys, time
from datetime import datetime, timezone
from pathlib import Path

JOB = json.load(open(os.path.join(os.path.dirname(__file__), "job.json")))
OUT = Path("/kaggle/working/illustrations")
(OUT / "imgs").mkdir(parents=True, exist_ok=True)

try:
    import torch
    from diffusers import AutoPipelineForText2Image
    HAVE = True
except Exception:
    HAVE = False

prompts = JOB.get("prompts", [])
model = JOB.get("model", "ByteDance/SDXL-Lightning")
steps = int(JOB.get("steps", 4))
seed_base = int(JOB.get("seed_base", 3000))

images = []
if HAVE:
    device = "cuda" if torch.cuda.is_available() else "cpu"
    pipe = AutoPipelineForText2Image.from_pretrained(model, torch_dtype=("float16" if device == "cuda" else "float32"))
    if device == "cuda":
        pipe.to("cuda")
    for i, p in enumerate(prompts):
        seed = seed_base + i
        t0 = time.perf_counter()
        out = pipe(prompt=p["prompt"], num_inference_steps=steps,
                   generator=torch.Generator(device=device).manual_seed(seed),
                   width=1280, height=720)
        secs = time.perf_counter() - t0
        fname = f"img_{p['seed']}.png"
        fpath = OUT / "imgs" / fname
        out.images[0].save(fpath, optimize=True)
        data = fpath.read_bytes()
        images.append({"file": fname, "path": str(fpath),
                       "sha256": hashlib.sha256(data).hexdigest(),
                       "bytes": len(data), "prompt": p["prompt"], "seed": seed,
                       "width": 1280, "height": 720, "model": model,
                       "seconds": round(secs, 4), "device": device})
else:
    for i, p in enumerate(prompts):
        seed = seed_base + i
        fname = f"img_{p['seed']}.png"
        fpath = OUT / "imgs" / fname
        fpath.write_bytes(b"placeholder-" + str(seed).encode())
        images.append({"file": fname, "path": str(fpath),
                       "sha256": hashlib.sha256(fpath.read_bytes()).hexdigest(),
                       "bytes": fpath.stat().st_size, "prompt": p["prompt"],
                       "seed": seed, "width": 1280, "height": 720, "model": model,
                       "seconds": 0.0, "device": "none"})

manifest = {"job_id": JOB.get("job_id"), "generator": "AI",
            "rights_basis": "ai_generated_illustration", "model": model,
            "device": "cuda" if (HAVE and torch.cuda.is_available()) else "cpu",
            "created_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "images": images}
(OUT / "manifest.json").write_text(json.dumps(manifest, indent=2))
print(f"illustration batch done: {len(images)} images")
'''


class IllustrationBatchTool(BaseTool):
    name = "illustration_batch"
    version = "0.1.0"
    tier = ToolTier.CORE
    capability = "illustration_batch"
    provider = "kaggle"
    stability = ToolStability.EXPERIMENTAL
    execution_mode = ExecutionMode.SYNC
    determinism = Determinism.STOCHASTIC
    runtime = ToolRuntime.API

    dependencies = ["cmd:kaggle"]
    install_instructions = "pip install kaggle. KAGGLE_API_TOKEN from env (never logged)."
    agent_skills = ["kaggle_bridge"]

    input_schema = {
        "type": "object", "required": ["command"],
        "properties": {
            "command": {"type": "string", "enum": ["run_batch"]},
            "kaggle_cmd": {"type": "string", "default": "kaggle"},
            "fake_kaggle": {"type": "string"},
            "job_folder": {"type": "string"},
            "job_id": {"type": "string"},
            "kernel_slug": {"type": "string"},
            "job": {"type": "object"},
            "enable_gpu": {"type": "boolean", "default": False},
            "enable_internet": {"type": "boolean", "default": False},
            "fetch_dest": {"type": "string"},
            "timeout": {"type": "integer", "default": 3600},
        },
    }

    def _kaggle(self, inputs: Dict[str, Any], args: List[str], timeout: int = 300) -> subprocess.CompletedProcess:
        fake = inputs.get("fake_kaggle")
        if fake:
            cmd = [sys.executable, fake] + args
        else:
            cmd = [inputs.get("kaggle_cmd", "kaggle")] + args
        return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)

    def execute(self, inputs: Dict[str, Any]) -> ToolResult:
        self.inputs = inputs
        command = inputs.get("command")
        if command != "run_batch":
            return ToolResult(success=False, error="BLOCKED: unknown command",
                              data={"verdict": "BLOCKED"})
        job_folder = Path(inputs.get("job_folder", ""))
        job_id = inputs.get("job_id")
        kernel_slug = inputs.get("kernel_slug")
        job = inputs.get("job") or {}
        fetch_dest = Path(inputs.get("fetch_dest", str(job_folder.parent / "output" / job_id)))
        if not all([job_folder, job_id, kernel_slug, job]):
            return ToolResult(success=False, error="BLOCKED: run_batch needs job_folder, job_id, kernel_slug, job",
                              data={"verdict": "BLOCKED"})

        job_folder.mkdir(parents=True, exist_ok=True)
        fetch_dest.mkdir(parents=True, exist_ok=True)

        # 1. build job folder (kernel-metadata.json + job.json + run.py)
        meta = {"id": kernel_slug, "title": "OpenMontage illustration batch",
                "code_file": "run.py", "language": "python", "kernel_type": "script",
                "is_private": True, "enable_gpu": bool(inputs.get("enable_gpu", False)),
                "enable_internet": bool(inputs.get("enable_internet", False)),
                "dataset_sources": [], "competition_sources": []}
        (job_folder / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
        job_record = dict(job); job_record["job_id"] = job_id
        job_record.setdefault("created_at", now_utc())
        (job_folder / "job.json").write_text(json.dumps(job_record, indent=2))
        (job_folder / "run.py").write_text(RUN_PY_TEMPLATE)

        # 2. push
        push = self._kaggle(inputs, ["kernels", "push", "-p", str(job_folder), "-t",
                             str(inputs.get("timeout", 3600)), "--accelerator",
                             "gpu" if inputs.get("enable_gpu") else "cpu"],
                            timeout=int(inputs.get("timeout", 3600)) + 60)
        if push.returncode != 0:
            return ToolResult(success=False, error=f"BLOCKED: push failed: {push.stderr[-300:]}",
                              data={"verdict": "BLOCKED"})

        # 3. fetch output (one call; no polling loop per M-rules)
        fo = self._kaggle(inputs, ["kernels", "output", str(kernel_slug), "-p", str(fetch_dest), "-q"],
                          timeout=300)
        if fo.returncode != 0 or not any(fetch_dest.iterdir()):
            return ToolResult(success=False, error=f"BLOCKED: fetch_output failed: {fo.stderr[-300:]}",
                              data={"verdict": "BLOCKED"})

        # 4. verify manifest job_id + sha256/bytes per file
        manifest_path = fetch_dest / "manifest.json"
        if not manifest_path.is_file():
            return ToolResult(success=False, error="REJECT: manifest.json missing",
                              data={"verdict": "REJECT"})
        manifest = json.loads(manifest_path.read_text())
        if manifest.get("job_id") != job_id:
            return ToolResult(success=False, error="REJECT: manifest job_id mismatch",
                              data={"verdict": "REJECT"})
        for ent in manifest.get("images", []):
            fpath = fetch_dest / ent["file"]
            if not fpath.is_file():
                return ToolResult(success=False, error=f"REJECT: missing {ent['file']}",
                                  data={"verdict": "REJECT"})
            if sha256_file(fpath) != ent["sha256"]:
                return ToolResult(success=False, error=f"REJECT: sha256 mismatch {ent['file']}",
                                  data={"verdict": "REJECT"})
            if ent.get("bytes") is not None and fpath.stat().st_size != ent["bytes"]:
                return ToolResult(success=False, error=f"REJECT: bytes mismatch {ent['file']}",
                                  data={"verdict": "REJECT"})

        # 5. apply Illustration label overlay to each image
        labeled = []
        for ent in manifest.get("images", []):
            src = fetch_dest / ent["file"]
            dst = fetch_dest / f"{src.stem}_labeled.png"
            apply_illustration_label(src, dst)
            labeled.append({"file": dst.name, "source": ent["file"],
                            "sha256": sha256_file(dst), "bytes": dst.stat().st_size})

        # 6. write local manifest (fetched + labeled)
        local_manifest = {
            "job_id": job_id, "kernel_slug": kernel_slug,
            "generator": "AI", "rights_basis": "ai_generated_illustration",
            "fetched_manifest": manifest,
            "labeled": labeled,
            "created_utc": now_utc(),
        }
        (fetch_dest / "batch_manifest.json").write_text(json.dumps(local_manifest, indent=2))

        return ToolResult(
            success=True, data={"verdict": "PASS", "job_id": job_id,
                                "images": len(manifest.get("images", [])),
                                "labeled": len(labeled),
                                "manifest": str(fetch_dest / "batch_manifest.json")},
            artifacts=[str(fetch_dest)],
        )
